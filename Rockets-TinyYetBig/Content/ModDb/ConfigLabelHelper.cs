using System;
using System.Collections.Generic;
using System.Text;

namespace Rockets_TinyYetBig.Content.ModDb
{
	internal class ConfigLabelHelper
	{
		public static List<string> GetHabitatConfigLabels()
		{
			return [
				STRINGS.OPTIONS_ROCKETRYEXPANDED.ENABLEEXTENDEDHABS.TITLE,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.COMPRESSINTERIORS.TITLE,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.CENTEREDINTERIORS.TITLE,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.HABITATPOWERPLUG.TITLE,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.HABITATINTERIORRADIATION.TITLE,
				];
		}

		public static List<string> GetAIOCargobayDescriptors()
		{
			var list = new List<string>
			{
				STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.GASCARGOBAYKGPERUNIT,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.LIQUIDCARGOBAYKGPERUNIT,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.SOLIDCARGOBAYKGPERUNIT,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.INSULATEDCARGOBAYS.TITLE,
			};
			return list;
		}

		public static List<string> GetLargeCargobayDescriptors(CargoBay.CargoType cargoType)
		{
			var list = new List<string>
			{
				STRINGS.OPTIONS_ROCKETRYEXPANDED.ENABLELARGECARGOBAYS.TITLE,
				STRINGS.OPTIONS_ROCKETRYEXPANDED.REBALANCEDCARGOCAPACITY.TITLE
			};
			switch (cargoType)
			{
				case CargoBay.CargoType.Solids:
					list.Add(STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.SOLIDCARGOBAYKGPERUNIT);
					break;

				case CargoBay.CargoType.Liquids:
					list.Add(STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.LIQUIDCARGOBAYKGPERUNIT);
					break;

				case CargoBay.CargoType.Gasses:
					list.Add(STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.GASCARGOBAYKGPERUNIT);
					break;
			}
			list.Add(STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAYUNITS.COLLOSSALCARGOBAYUNITS);
			list.Add(STRINGS.OPTIONS_ROCKETRYEXPANDED.INSULATEDCARGOBAYS.TITLE);
			list.Add(STRINGS.OPTIONS_ROCKETRYEXPANDED.CARGOBAY_LOGICPORTS.TITLE);

			return list;
		}
	}
}

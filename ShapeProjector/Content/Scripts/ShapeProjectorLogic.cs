namespace ShapeProjector.Content.Scripts
{
	public class ShapeProjectorLogic : KMonoBehaviour, ISaveLoadable
	{
		#region saveload
		public struct SaveloadShapeData
		{
			public string shapeId;
			public int width, height;
			public bool isActive, linkedDimensions, isThicc;
		}
		public class ShapeData
		{
			public static ShapeData FromSerializable(SaveloadShapeData data)
			{
				return new ShapeData()
				{
					shapeId = data.shapeId,
					width = data.width,
					height = data.height,
					isActive = data.isActive,
					isThicc = data.isThicc,
					linkedDimensions = data.linkedDimensions
				};
			}
			public SaveloadShapeData ToSerializable()
			{
				return new SaveloadShapeData()
				{
					shapeId = this.shapeId,
					width = this.width,
					height = this.height,
					isActive = this.isActive,
					isThicc = this.isThicc,
					linkedDimensions = this.linkedDimensions
				};
			}
			public string shapeId;
			public int width, height;
			public bool isActive, linkedDimensions, isThicc;
		}
		[System.Runtime.Serialization.OnSerializing]
		public void OnSerializing()
		{
			saveLoadActiveShapes = new SaveloadShapeData[ActiveShapes.Count];
			for (int index = 0; index < this.ActiveShapes.Count; ++index)
			{
				saveLoadActiveShapes[index] = this.ActiveShapes[index].ToSerializable();
			}
		}

		[System.Runtime.Serialization.OnDeserialized]
		public void OnDeserialized()
		{
			foreach (var activeShape in this.saveLoadActiveShapes)
			{
				ActiveShapes.Add(ShapeData.FromSerializable(activeShape));
			}
		}
		private SaveloadShapeData[] saveLoadActiveShapes = [];
		#endregion


		#region BlueprintsV2 Integration
		/// <summary>
		/// This static method will allow you to apply any additional data stored previously in Blueprints_GetData.
		/// </summary>
		/// <param name="source">The Gameobject of the newly constructed building</param>
		/// <param name="data">the additional data stored in the object that was generated by Blueprints_GetData</param>
		public static void Blueprints_SetData(GameObject source, JObject data)
		{
			if (source.TryGetComponent<ShapeProjectorLogic>(out var behavior))
			{
				if (data.TryGetTokenValue<string>("HighlightColor", out string hexcolor))
				{
					behavior.SetHighlightColor(Util.ColorFromHex(hexcolor));
				}
				if (data.TryGetTokenValue<string>("ActiveShapes", out string serializedShapes))
				{
					behavior.ApplySerializedShapes(serializedShapes);
				}
			}
		}

		/// <summary>
		/// This static method takes in the source gameobject and returns a JObject with all the additional data you give it. this data is then stored in the blueprint
		/// </summary>
		/// <param name="source">the gameobject the blueprint is made from</param>
		/// <returns>JObject of all the data to be stored in the blueprint</returns>
		public static JObject Blueprints_GetData(GameObject source)
		{
			if (source.TryGetComponent<ShapeProjectorLogic>(out var behavior))
			{
				return new JObject()
				{
					{ "HighlightColor", Util.ToHexString(behavior.HighlightColor)},
					{ "ActiveShapes", behavior.GetSerializedShapes()},
				};
			}
			return null;
		}

		string GetSerializedShapes()
		{
			List<SaveloadShapeData> serializableShapes = new List<SaveloadShapeData>();
			foreach (var shape in ActiveShapes)
			{
				serializableShapes.Add(shape.ToSerializable());
			}
			try
			{
				return JsonConvert.SerializeObject(serializableShapes);
			}
			catch (Exception e)
			{
				SgtLogger.error($"Error serializing shapes: {e.Message}");
				return null;
			}
		}
		void ApplySerializedShapes(string jsonData)
		{
			List<SaveloadShapeData> serializableShapes = new List<SaveloadShapeData>();
			try
			{
				serializableShapes = JsonConvert.DeserializeObject<List<SaveloadShapeData>>(jsonData);
			}
			catch (Exception e)
			{
				SgtLogger.error($"Error deserializing shapes: {e.Message}");
			}
			ActiveShapes.Clear();
			foreach (var shape in serializableShapes)
			{
				ActiveShapes.Add(ShapeData.FromSerializable(shape));
			}
			RefreshCells();
		}
		#endregion

		[MyCmpGet] KBatchedAnimController kbac;
		[MyCmpAdd] CopyBuildingSettings cbs;

		[Serialize] public readonly List<ShapeData> ActiveShapes = [];
		readonly List<string> Tintables = ["tintable_bloom", "tintable_fx", "tintable_off"];
		[Serialize] public Color HighlightColor = Color.white;

		ShapeProjectorVisualizerEffect visualizer;

		readonly HashSet<int> projectedCells = new HashSet<int>();

		public override void OnSpawn()
		{
			base.OnSpawn();
			DisableConnectors();
			if (ActiveShapes.Count > 0)
			{
				kbac.Play("working_loop", KAnim.PlayMode.Loop);
			}
			RefreshTint();
			RefreshDisplay();
			visualizer = CameraController.Instance.overlayNoDepthCamera.gameObject.AddComponent<ShapeProjectorVisualizerEffect>();
			visualizer.SetMaster(this);
			this.Sub(GameHashes.CopySettings, OnCopySettings);
		}
		private void OnCopySettings(object obj)
		{
			if(obj is GameObject other && other.TryGetComponent<ShapeProjectorLogic>(out var otherLogic))
			{
				bool hasShapesBefore = this.ActiveShapes.Count > 0;
				this.ActiveShapes.Clear();
				foreach (var shape in otherLogic.ActiveShapes)
				{
					this.ActiveShapes.Add(new ShapeData()
					{
						shapeId = shape.shapeId,
						width = shape.width,
						height = shape.height,
						isActive = shape.isActive,
						isThicc = shape.isThicc,
						linkedDimensions = shape.linkedDimensions
					});
				}
				this.HighlightColor = otherLogic.HighlightColor;
				RefreshTint();
				RefreshDisplay();
				if(hasShapesBefore && this.ActiveShapes.Count == 0)
				{
					kbac.Play("working_pst");
					kbac.Queue("off");
				}
				else if (!hasShapesBefore && this.ActiveShapes.Count > 0)
				{
					kbac.Play("working_pre");
					kbac.Queue("working_loop", KAnim.PlayMode.Loop);
				}
			}
		}

		void RefreshTint()
		{
			foreach (var symbol in Tintables)
			{
				kbac.SetSymbolTint(symbol, HighlightColor);
			}
		}
		public override void OnCleanUp()
		{
			this.UnsubAll();
			if (visualizer != null)
			{
				Destroy(visualizer);
			}
			base.OnCleanUp();
		}
		#region disable connectors

		private static readonly KAnimHashedString[] leftSymbols =
		[
	new KAnimHashedString("joint_left"),
	new KAnimHashedString("joint_left_fg"),
	new KAnimHashedString("joint_left_place")
		];
		private static readonly KAnimHashedString[] rightSymbols =
		[
	new KAnimHashedString("joint_right"),
	new KAnimHashedString("joint_right_fg"),
	new KAnimHashedString("joint_right_place")
		];
		private static readonly KAnimHashedString[] topSymbols =
		[
	new KAnimHashedString("joint_top"),
	new KAnimHashedString("joint_top_fg"),
	new KAnimHashedString("joint_top_place")
		];
		private static readonly KAnimHashedString[] bottomSymbols =
		[
	new KAnimHashedString("joint_bottom"),
	new KAnimHashedString("joint_bottom_fg"),
	new KAnimHashedString("joint_bottom_place")
		];
		void DisableConnectors()
		{
			foreach (var symbol in leftSymbols)
				kbac.SetSymbolVisiblity(symbol, false);
			foreach (var symbol in rightSymbols)
				kbac.SetSymbolVisiblity(symbol, false);
			foreach (var symbol in topSymbols)
				kbac.SetSymbolVisiblity(symbol, false);
			foreach (var symbol in bottomSymbols)
				kbac.SetSymbolVisiblity(symbol, false);
		}
		#endregion

		internal int CurrentShapeCount() => ActiveShapes.Count;
		public ShapeData GetShapeData(int index)
		{
			if (index < 0 || index >= ActiveShapes.Count)
			{
				throw new IndexOutOfRangeException($"Index {index} is out of range for ActiveShapes with count {ActiveShapes.Count}");
			}
			return ActiveShapes[index];
		}

		internal void RefreshVisibility(ShapeData currentData) => RefreshDisplay();

		internal void RefreshDimensions(ShapeData currentData) => RefreshDisplay();
		public void RefreshDisplay()
		{
			SoundEvent.PlayOneShot(GlobalAssets.GetSound("RangeVisualization_movement"), transform.GetPosition());
			RefreshCells();

		}
		void RefreshCells()
		{
			projectedCells.Clear();
			foreach (var shape in ActiveShapes)
			{
				if (shape.isActive)
					ModAssets.CalculateShape(Grid.PosToCell(this), shape.shapeId, shape, projectedCells);
			}
		}

		internal void RemoveShape(ShapeData currentData)
		{
			ActiveShapes.Remove(currentData);
			if (ActiveShapes.Count == 0)
			{
				kbac.Play("working_pst");
				kbac.Queue("off");
			}
			RefreshCells();
			//throw new NotImplementedException();
		}
		internal void AddShape(ShapeData data)
		{
			bool hadShapesBefore = ActiveShapes.Count > 0;
			ActiveShapes.Add(data);
			if (!hadShapesBefore)
			{
				kbac.Play("working_pre");
				kbac.Queue("working_loop", KAnim.PlayMode.Loop);
			}
			RefreshCells();
		}

		internal ShapeData AddNewShape()
		{
			var data = new ShapeData()
			{
				shapeId = ModAssets.Shape_Circle_ID,
				width = 5,
				height = 5,
				isActive = true,
				linkedDimensions = true
			};
			AddShape(data);
			return data;
		}

		internal HashSet<int> GetActiveCells() => projectedCells;

		internal void SetHighlightColor(Color tint)
		{
			HighlightColor = tint;
			RefreshTint();
		}
	}
}
